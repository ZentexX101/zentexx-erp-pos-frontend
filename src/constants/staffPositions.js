export const positionByValue = (value) => POSITIONS.find((position) => position.value === value) ?? null;

// An existing staff member's position, read back from role + designation
export const positionOf = (staff) => {
  if (!staff) return "";
  if (staff.role === "admin") return "admin";
  const byTitle = POSITIONS.find(
    (position) => !position.admin && position.value !== "other" && position.label.toLowerCase() === staff.designation?.trim().toLowerCase(),
  );
  if (byTitle) return byTitle.value;
  return staff.isManager ? "manager" : "other";
};
